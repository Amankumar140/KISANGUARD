// Helper to get farmers by crop
export const getFarmersByCrop = (cropId) => {
  return MOCK_FARMERS_FULL.filter(f => f.produce.some(p => p.cropId === cropId));
};

// Helper to get total supply for a crop
export const getTotalSupplyForCrop = (cropId) => {
  return MOCK_FARMERS_FULL.reduce((total, farmer) => {
    const crop = farmer.produce.find(p => p.cropId === cropId);
    return total + (crop ? crop.quantityKg : 0);
  }, 0);
};
